# -*- coding: utf-8 -*-
"""Generates the repo-root sitemap.xml and robots.txt (Milestone 2.4).

sitemap.xml lists exactly the 13 approved canonical page URLs -- the 12 legacy
pages plus the new floor-assessments-inspections.html page, all at their
established .html filenames (2026-07-23: assessment page's canonical
changed from extensionless to .html to match the legacy pages' format).
No lastmod is emitted: the repo has no
reliable per-page content-modification source (git history tracks regeneration,
not content change), and an invented date would be worse than none.
changefreq/priority are deliberately omitted (ignored by Google, noise otherwise).

Final pre-launch SEO milestone (2026-07-24): each <url> entry now also carries
<image:image>/<image:loc> children for that page's meaningful, public
project/service images. The mapping is read from the just-generated pages
themselves (build_all.py runs this script LAST, so the pages are the current
authoritative output of build/data + build/scripts): every local <img> with a
non-empty alt, in document order, deduplicated per page. Excluded by rule:
external images (YouTube thumbnails belong to sitemap-videos.xml), images with
empty alt (this repo's established decorative-image convention -- site logo
mark, JS lightbox placeholder), and the site chrome logo/badge files. Every
included image is asserted to exist on disk. Only current Google-supported
tags are emitted (image:loc; caption/title/license were deprecated in 2022).

robots.txt allows everything and points at the production sitemap plus the
video sitemap (sitemap-videos.xml, generated by build_videos.py from the same
youtube_videos.json snapshot the VideoObject schema uses). All files are
deterministic so the CI regenerate-and-diff gate stays green.
"""
import html as _html
import re
import urllib.parse
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent.parent  # -> repo root

# Site-chrome image files that are never project/service content.
_EXCLUDED_IMAGE_FILES = {"LOGO-2025.png", "bonacc.jpeg", "favicon.ico",
                         "favicon-192.ico", "favicon-512.ico"}

_IMG_TAG_RE = re.compile(r"<img\b[^>]*>")
_SRC_RE = re.compile(r'\bsrc="([^"]*)"')
_ALT_RE = re.compile(r'\balt="([^"]*)"')


def page_images(page_file):
    """Ordered, deduplicated absolute URLs of the page's meaningful public
    images (local, non-empty alt, not site chrome). Asserts every mapped
    file exists on disk."""
    text = (REPO_ROOT / page_file).read_text(encoding="utf-8")
    seen, urls = set(), []
    for tag in _IMG_TAG_RE.findall(text):
        src_m = _SRC_RE.search(tag)
        alt_m = _ALT_RE.search(tag)
        if not src_m:
            continue
        src = _html.unescape(src_m.group(1))
        if not src or src.startswith(("http://", "https://", "data:")):
            continue  # external (video thumbnails) or inline -- not ours to map
        if alt_m is None or not alt_m.group(1).strip():
            continue  # decorative by this repo's convention
        rel = src.lstrip("/")
        if rel.split("/")[-1] in _EXCLUDED_IMAGE_FILES:
            continue
        f = REPO_ROOT / rel
        assert f.is_file(), f"{page_file}: sitemap image missing on disk: {src}"
        url = "https://www.sdhardwoods.com/" + urllib.parse.quote(rel, safe="/")
        if url not in seen:
            seen.add(url)
            urls.append(url)
    assert len(urls) <= 1000, f"{page_file}: exceeds 1000 images per sitemap URL"
    return urls

# The approved canonical URL map (Milestone 2.4). One entry per page, exactly 13.
CANONICAL_URLS = [
    "https://www.sdhardwoods.com/",
    "https://www.sdhardwoods.com/deep-cleaning-hardwood-floors-san-diego.html",
    "https://www.sdhardwoods.com/recent_project_photo_gallery_1.html",
    "https://www.sdhardwoods.com/recent_project_photo_gallery_2.html",
    "https://www.sdhardwoods.com/recent_project_photo_gallery_3.html",
    "https://www.sdhardwoods.com/recent_project_photo_gallery_4.html",
    "https://www.sdhardwoods.com/recent_project_gallery_5.html",
    "https://www.sdhardwoods.com/solid_wood_floor_photo_gallery.html",
    "https://www.sdhardwoods.com/videos_of_refinishing_process.html",
    "https://www.sdhardwoods.com/about_us.html",
    "https://www.sdhardwoods.com/blog.html",
    "https://www.sdhardwoods.com/contact_us.html",
    "https://www.sdhardwoods.com/floor-assessments-inspections.html",
]

ROBOTS_TXT = """User-agent: *
Allow: /

Sitemap: https://www.sdhardwoods.com/sitemap.xml
Sitemap: https://www.sdhardwoods.com/sitemap-videos.xml
"""


def main():
    assert len(CANONICAL_URLS) == 13, "canonical map must contain exactly 13 URLs"
    assert len(set(CANONICAL_URLS)) == 13, "canonical map contains a duplicate URL"
    for u in CANONICAL_URLS:
        assert u.startswith("https://www.sdhardwoods.com/"), f"non-canonical origin: {u}"

    entries = []
    total_images = 0
    for u in CANONICAL_URLS:
        page_file = u.replace("https://www.sdhardwoods.com/", "") or "index.html"
        imgs = page_images(page_file)
        total_images += len(imgs)
        img_xml = "".join(
            f"\n    <image:image>\n      <image:loc>{loc}</image:loc>\n    </image:image>"
            for loc in imgs
        )
        entries.append(f"  <url>\n    <loc>{u}</loc>{img_xml}\n  </url>")
    sitemap = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n'
        '        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n'
        + "\n".join(entries) + "\n"
        "</urlset>\n"
    )

    sitemap_path = REPO_ROOT / "sitemap.xml"
    with open(sitemap_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(sitemap)
    print(f"Wrote {sitemap_path} ({len(CANONICAL_URLS)} URLs, {total_images} images)")

    robots_path = REPO_ROOT / "robots.txt"
    with open(robots_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(ROBOTS_TXT)
    print(f"Wrote {robots_path}")


if __name__ == "__main__":
    main()
